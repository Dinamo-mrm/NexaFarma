-- Estas tablas quedan SIN RLS habilitado (equivalente a como se comportan en
-- MySQL: sin control de fila). Esto es correcto si la app Spring Boot se
-- conecta por JDBC directo con sus propias credenciales de Postgres.
-- Si en algun momento se expone alguna tabla via la API automatica de
-- Supabase (PostgREST) a clientes que no sean el backend Spring Boot,
-- se debera habilitar RLS y definir politicas antes de eso, por ejemplo:
--   ALTER TABLE ventas ENABLE ROW LEVEL SECURITY;
